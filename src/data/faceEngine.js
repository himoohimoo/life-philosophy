// ==================== 伪随机数生成器 ====================

/**
 * 基于种子的伪随机数生成器（Mulberry32）
 * @param {number} seed - 随机种子
 * @returns {Function} 返回0-1之间的随机数
 */
function createSeededRandom(seed) {
  let s = seed | 0;
  return function () {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * 根据图片数据和日期生成种子
 * @param {string} imageData - 图片base64字符串
 * @returns {number} 随机种子
 */
function generateSeed(imageData) {
  // 取图片数据的前1000个字符做简单hash
  const str = imageData.substring(0, 1000);
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // 转为32位整数
  }
  // 加上日期信息（同一天同一张图结果一致）
  const today = new Date();
  const dateStr = `${today.getFullYear()}-${today.getMonth() + 1}-${today.getDate()}`;
  let dateHash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    dateHash = ((dateHash << 5) - dateHash) + dateStr.charCodeAt(i);
    dateHash = dateHash & dateHash;
  }
  return (hash ^ dateHash) >>> 0;
}

/**
 * 从数组中按种子随机选取
 */
function pick(random, arr) {
  return arr[Math.floor(random() * arr.length)];
}

/**
 * 生成指定范围的随机整数
 */
function randInt(random, min, max) {
  return Math.floor(random() * (max - min + 1)) + min;
}

