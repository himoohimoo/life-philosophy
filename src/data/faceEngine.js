/**
 * 生成五行分析数据
 */
function generateFiveElements(random) {
  // 生成5个随机值，然后归一化到100
  const raw = [
    random() * 10 + 5,
    random() * 10 + 5,
    random() * 10 + 5,
    random() * 10 + 5,
    random() * 10 + 5,
  ];
  const total = raw.reduce((a, b) => a + b, 0);
  const normalized = raw.map(v => Math.round((v / total) * 100));
  // 修正总和为100
  const diff = 100 - normalized.reduce((a, b) => a + b, 0);
  normalized[0] += diff;

  return {
    metal: normalized[0],
    wood: normalized[1],
    water: normalized[2],
    fire: normalized[3],
    earth: normalized[4],
  };
}
